function toNumeric(val: string): number {
  const n = parseFloat(val);
  return isNaN(n) ? 0 : n;
}

function toWebsite(val: string | null): string | null {
  if (!val || val === '-' || val === 'null') return null;
  return val;
}

async function loadEnvLocal() {
  try {
    const fs = await import('fs');
    const path = await import('path');
    const envPath = path.resolve(process.cwd(), '.env.local');
    const raw = fs.readFileSync(envPath, 'utf-8');
    for (const line of raw.split('\n')) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const eqIdx = trimmed.indexOf('=');
      if (eqIdx === -1) continue;
      const key = trimmed.slice(0, eqIdx).trim();
      const val = trimmed.slice(eqIdx + 1).trim();
      if (!process.env[key]) process.env[key] = val;
    }
  } catch {}
}

async function seedCompleteLeads() {
  await loadEnvLocal();

  const targetUrl =
    process.env.GOOGLE_SHEETS_WEBAPP_URL ||
    process.env.NEXT_PUBLIC_LEADS_SHEET_API ||
    '';

  if (!targetUrl) {
    console.error('ERROR: GOOGLE_SHEETS_WEBAPP_URL belum dikonfigurasi di .env.local');
    process.exit(1);
  }

  console.log('===============================================================');
  console.log('SEEDING COMPLETE REAL OUTREACH CONTACTS TO GOOGLE SHEETS CRM');
  console.log('===============================================================\n');
  console.log(`Endpoint: ${targetUrl}`);
  console.log(`Total leads to seed: ${allLeads.length}\n`);

  const now = new Date().toISOString();

  const formattedLeads = allLeads.map((l) => ({
    business_name: l.name,
    category: l.category,
    phone_number: l.phone === '-' ? '' : l.phone,
    maps_url: l.mapsUrl === '-' ? '' : l.mapsUrl,
    rating: toNumeric(l.rating),
    review_count: toNumeric(l.reviews),
    website: toWebsite(l.website),
    lead_status: l.status,
    rejection_reason: l.rejection === '-' ? '' : l.rejection,
    generated_pitch: l.pitch,
    last_sync_at: now,
  }));

  const statusBreakdown: Record<string, number> = {};
  formattedLeads.forEach((l) => {
    statusBreakdown[l.lead_status] = (statusBreakdown[l.lead_status] || 0) + 1;
  });

  console.log('STATUS BREAKDOWN:');
  Object.entries(statusBreakdown)
    .sort((a, b) => b[1] - a[1])
    .forEach(([status, count]) => {
      console.log(`  ${status.padEnd(20)} ${count}`);
    });
  console.log('');

  console.log('Sending bulk_resync to Google Sheets...');

  try {
    const res = await fetch(targetUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        action: 'bulk_resync',
        leads: formattedLeads,
      }),
    });

    const json = await res.json().catch(() => null);

    if (res.ok && json?.status === 'success') {
      console.log(`\nSUCCESS: ${json.inserted || formattedLeads.length} leads inserted into "Leads CRM" tab.`);
      console.log('Dashboard will now show these 85 real contacts on next Sync Sheet / page reload.');
    } else {
      console.error('FAILED:', json);
      process.exit(1);
    }
  } catch (err) {
    console.error('Network error:', err);
    process.exit(1);
  }
}

